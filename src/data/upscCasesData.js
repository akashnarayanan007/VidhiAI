// Filter for entries that have null/undefined fields or are placeholders
export function getValidCases() {
  return UPSC_CASES.filter(c => c.facts && c.judgment && c.significance && c.facts.length > 5);
}

export function getCaseById(name) {
  return UPSC_CASES.find(c => c.name.toLowerCase().includes(name.toLowerCase()));
}

export function getCasesByTag(tag) {
  return UPSC_CASES.filter(c => c.tags?.some(t => t.toLowerCase().includes(tag.toLowerCase())));
}

export function getCaseCount() {
  return getValidCases().length;
}

